const t=(await (await fetch('http://127.0.0.1:9333/json/list')).json()).find(p => p.type==='page' && !p.url.includes('widget'));
const ws = new WebSocket(t.webSocketDebuggerUrl); let id=0; const pend={}; const logs=[];
ws.onmessage=e=>{const m=JSON.parse(e.data); if(m.id&&pend[m.id]) pend[m.id](m.result); else if(m.method==='Runtime.exceptionThrown') logs.push(JSON.stringify(m.params.exceptionDetails).slice(0,600)); else if(m.method==='Runtime.consoleAPICalled') logs.push(m.params.type+': '+m.params.args.map(a=>a.value||a.description).join(' ').slice(0,400));};
await new Promise(r=>ws.onopen=r);
const send=(method,params={})=>new Promise(r=>{const i=++id; pend[i]=r; ws.send(JSON.stringify({id:i,method,params}));});
await send('Runtime.enable');
const r = await send('Runtime.evaluate',{expression:`try { document.querySelectorAll('[data-act="toggleStep"]')[0].click(); 'clicked ' + document.querySelector('.prog b').textContent + ' hidden=' + document.hidden + ' vis=' + document.visibilityState } catch(e) { 'ERR '+e.stack }`, returnByValue:true});
console.log(r.result.value);
await new Promise(r=>setTimeout(r,800));
console.log(logs.join('\n'));
ws.close();
